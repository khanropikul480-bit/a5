                <div class="faq-accordion" id="faqAccordion">
                    <div class="faq-item">
                        <button class="faq-question" aria-expanded="false">
                            <span>How does hand saddle stitching differ from sewing machine stitching?</span>
                            <span class="faq-chevron">&plus;</span>
                        </button>
                        <div class="faq-answer">
                            <p>Hand saddle stitching (point sellier) employs two needles traversing the same diamond-shaped awl hole from opposite directions with a single length of waxed flax linen thread. If an external stitch strand is cut, the seam will never unravel because the opposing strand remains frictionally locked within the hide. In contrast, sewing machines use interlocking top and bottom loops that rapidly unzip if a single thread breaks.</p>
                        </div>
                    </div>

                    <div class="faq-item">
                        <button class="faq-question" aria-expanded="false">
                            <span>Why do you use vegetable-tanned leather instead of chrome-tanned leather?</span>
                            <span class="faq-chevron">&plus;</span>
                        </button>
                        <div class="faq-answer">
                            <p>Vegetable tanning uses natural tree bark tannins (chestnut, mimosa, oak) over a slow 60-day pit immersion process. It preserves the natural collagen density of the hide, allowing it to develop a rich organic patina, hold crisp beveled edges, and last for a century. Chrome tanning is a 24-hour industrial chemical shortcut using heavy metals that produces thin, stretchy leather incapable of developing authentic patina.</p>
                        </div>
                    </div>

                    <div class="faq-item">
                        <button class="faq-question" aria-expanded="false">
                            <span>How do I care for and condition my IvorySatchelRidge bag?</span>
                            <span class="faq-chevron">&plus;</span>
                        </button>
                        <div class="faq-answer">
                            <p>We recommend applying a light coat of pure botanical beeswax and jojoba oil conditioning balm twice a year. Keep your bag away from direct radiators and prolonged rain. If caught in heavy rain, gently blot moisture with a dry microfiber towel and let dry naturally at room temperature. Never use chemical cleaners or petroleum-based polishes.</p>
                        </div>
                    </div>

                    <div class="faq-item">
                        <button class="faq-question" aria-expanded="false">
