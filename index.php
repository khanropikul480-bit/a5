        <!-- Section 7: The Saddle Stitching Bench Protocol -->
        <section class="stitching-bench-section section-spacing bg-secondary-tint" id="stitchingBench">
            <div class="container">
                <div class="section-header-centered">
                    <div class="section-badge">Artisan Protocol</div>
                    <h2 class="section-heading">Why Two Needles Beat Automated Sewing Machines</h2>
                    <p class="section-subheading">Understanding the physical mechanics behind point sellier durability versus industrial lockstitching.</p>
                </div>

                <div class="stitching-comparison-grid">
                    <div class="comparison-visual">
                        <img src="images/bag-leather-saddle-stitch-detail.jpg" alt="Macro view of hand saddle stitching" loading="lazy">
                        <div class="visual-badge">9 Stitches Per Inch &bull; Lin Câblé No. 432</div>
                    </div>
                    <div class="comparison-details">
                        <div class="comp-point">
                            <h4>Dual Traversing Strands</h4>
                            <p>Unlike sewing machines where top and bottom threads merely hook around each other in the middle, saddle stitching drives two separate strands completely through the full hide thickness from opposing sides.</p>
                        </div>
                        <div class="comp-point">
                            <h4>No Domino Seam Unraveling</h4>
                            <p>If a machine stitch thread breaks, slight friction unzips the entire seam. If a saddle stitch is severed by a blade, the opposing strand remains frictionally locked within the awl hole, holding the seam intact.</p>
                        </div>
                        <div class="comp-point">
                            <h4>Organic Beeswax Infiltration</h4>
                            <p>Every thread length is hand-waxed with raw botanical beeswax before stitching, lubricating the flax fibrils and sealing the hole against environmental moisture and dust.</p>
                        </div>
                    </div>
                </div>
            </div>
        </section>

